#!/bin/sh
# Print each relay's live egress IP and the single client URL for the whole
# pool.
#
# Every relay sits behind one listener: host port 3100 forwards to the relay
# app's container port (BASE_PORT, normally 3000). A client dials that one URL
# and the router picks a lane per request; there is no per-relay port any more.
# The URL uses the router's actual host bind, parsed from the generated
# docker-compose.yml (the wizard sets INGRESS_BIND to the VPS Tailscale IP for
# mesh installs; the safe default bind is 127.0.0.1, which is not reachable
# from the tailnet and is reported as such). A Quick-Tunnel URL replaces it
# when a tunnel container exists (graceful when absent).
#
# Usage: ./get-status.sh [count]     (default COUNT env, else 10)
# Missing/stopped containers print "(not ready)" and never abort the table
# (safe under `set -e` callers too).
set -u

# Operate on the checkout this script lives in, not the caller's CWD.
POOL_DIR="${POOL_DIR:-$(cd "$(dirname "$0")" && pwd)}"
cd "$POOL_DIR" || exit 1

COUNT="${1:-${COUNT:-10}}"

case "$COUNT" in
  ''|*[!0-9]*)
    echo "error: count must be an integer 1..64, got '$COUNT'" >&2
    exit 1
    ;;
esac
if [ "$COUNT" -lt 1 ] || [ "$COUNT" -gt 64 ]; then
  echo "error: count must be an integer 1..64, got '$COUNT'" >&2
  exit 1
fi

# Host binds as generated by generate-compose.sh: SOCKS probes must dial the
# bind that actually listens (an interface-specific WARP_BIND has no loopback
# listener), and the client URL must use the router bind. Defaults mirror the
# generator's loopback binds when no compose file exists.
SOCKS_BIND="$(sed -n 's/^ *- "\([^":]*\):[0-9][0-9]*:1080"$/\1/p' docker-compose.yml 2>/dev/null | head -n 1)"
[ -n "$SOCKS_BIND" ] || SOCKS_BIND="127.0.0.1"
# The host port is generated (ROUTER_PORT, default 3100), so parse it instead
# of assuming it: the client URL must carry the port that actually listens.
ROUTER_LINE="$(sed -n '/:1080"$/! s/^ *- "\([^":]*\):\([0-9][0-9]*\):[0-9][0-9]*"$/\1 \2/p' docker-compose.yml 2>/dev/null | head -n 1)"
ROUTER_BIND="${ROUTER_LINE% *}"
ROUTER_PORT="${ROUTER_LINE#* }"
[ -n "$ROUTER_BIND" ] || ROUTER_PORT=""
# Direct public-IP ingress marker: compose bakes RELAY_DIRECT_PUBLIC=1 and
# the Basic credentials, so the client URL can be printed with embedded creds.
DIRECT_PUBLIC="$(sed -n 's/^ *- RELAY_DIRECT_PUBLIC=1$/direct/p' docker-compose.yml 2>/dev/null | head -n 1)"
PROXY_AUTH_VALUE="$(sed -n 's/^ *- RELAY_PROXY_AUTH=\([^"].*\)$/\1/p' docker-compose.yml 2>/dev/null | head -n 1)"

tunnel_url() {
  docker logs "warp-relay-tunnel-$1" 2>&1 \
    | grep -oE 'https://[a-zA-Z0-9.-]+\.trycloudflare\.com' \
    | tail -n 1 || true
}

egress_ip() {
  # 1. Fast host-side SOCKS5 probe (works for warp-lite and standard containers)
  socks_port=$((10800 + $1))
  ip="$(curl -s -m 4 -x "socks5h://${SOCKS_BIND}:${socks_port}" https://cloudflare.com/cdn-cgi/trace 2>/dev/null | sed -n 's/^ip=//p')"
  if [ -n "$ip" ]; then
    printf '%s' "$ip"
    return
  fi
  # 2. In-container docker exec fallback
  docker exec "warp-relay-warp-$1" curl -s -m 8 https://cloudflare.com/cdn-cgi/trace 2>/dev/null \
    | sed -n 's/^ip=//p' || true
}

mesh_ip() {
  if command -v tailscale >/dev/null 2>&1; then
    tailscale ip -4 2>/dev/null | head -n 1 || true
  fi
}

# Startup grace: `compose up` returns before WireGuard handshakes complete, so
# a status run right after a (re)start would print a wall of "(not ready)".
# Poll container health first, bounded (GET_STATUS_WAIT_S, default 60s, 0
# disables) so a genuinely dead relay still prints instead of hanging.
WAIT_S="${GET_STATUS_WAIT_S:-60}"
case "$WAIT_S" in ''|*[!0-9]*) WAIT_S=60 ;; esac
if [ "$WAIT_S" -gt 0 ] && command -v docker >/dev/null 2>&1; then
  waited=0
  while [ "$waited" -lt "$WAIT_S" ]; do
    pending=0
    j=1
    while [ "$j" -le "$COUNT" ]; do
      state="$(docker inspect -f '{{if .State.Health}}{{.State.Health.Status}}{{else}}none{{end}}' "warp-relay-warp-${j}" 2>/dev/null || echo missing)"
      case "$state" in healthy|none) ;; *) pending=$((pending + 1)) ;; esac
      j=$((j + 1))
    done
    [ "$pending" -eq 0 ] && break
    sleep 5
    waited=$((waited + 5))
  done
  [ "$pending" -ne 0 ] && echo "note: ${pending} relay(s) still starting after ${waited}s (they recover on their own; the router skips them meanwhile)." && echo ""
fi

echo "=== WARP relay status (1..${COUNT}) ==="
printf "%-10s %s\n" "INSTANCE" "EGRESS IP"
echo "------------------------------------------------------------"

SEEN_IPS=""
DUP_IPS=""
i=1
while [ "$i" -le "$COUNT" ]; do
  # Egress address is a property of the WARP client container, so read it there
  # rather than through the relay app.
  IP="$(egress_ip "$i")"
  [ -z "$IP" ] && IP="(not ready)"
  case "$IP" in
    "(not ready)"|"") ;;
    *)
      case " ${SEEN_IPS} " in
        *" ${IP} "*) DUP_IPS="${DUP_IPS} ${IP}" ;;
        *) SEEN_IPS="${SEEN_IPS} ${IP}" ;;
      esac
      ;;
  esac

  printf "%-10s %s\n" "warp-${i}" "$IP"
  i=$((i + 1))
done
if [ -n "$DUP_IPS" ]; then
  echo ""
  echo "note: relays share egress IP(s)${DUP_IPS} — expected on IPv4 (Cloudflare"
  echo "      WARP CGNAT); per-relay isolation is per-IPv6 egress address."
fi

# Keep-cold scheduler state (bounded, read-only). The prober writes
# RELAY_STATE_FILE; CI and fresh checkouts have neither node nor the file, and
# both cases must stay silent rather than fail the table above. Nothing here
# reads an egress address — the state holds relay indexes, models and
# timestamps only, and that is all this section may print.
STATE_FILE="${RELAY_STATE_FILE:-.keep-cold/state.json}"
if command -v node >/dev/null 2>&1 && [ -f "$STATE_FILE" ]; then
  STATE_FILE="$STATE_FILE" RELAY_COUNT="$COUNT" node -e '
const fs = require("fs");
let state;
try {
  state = JSON.parse(fs.readFileSync(process.env.STATE_FILE, "utf8"));
} catch (err) {
  process.exit(0);
}
const relays = state && typeof state === "object" ? state.relays : null;
if (!relays || typeof relays !== "object") process.exit(0);
const count = Number(process.env.RELAY_COUNT) || 0;
const nowSec = Date.now() / 1000;
const epochSec = function (value) {
  const n = Number(value);
  if (!Number.isFinite(n) || n <= 0) return 0;
  return n > 1e11 ? Math.round(n / 1000) : Math.round(n);
};
const rows = [];
const hourAgo = nowSec - 3600;
for (let i = 1; i <= count; i += 1) {
  const rec = relays[String(i)] || relays["warp-" + i];
  if (!rec || typeof rec !== "object") continue;
  const failures = Number(rec.consecutiveFailures) || 0;
  const until = epochSec(rec.cooldownUntil);
  const cooling = until > nowSec ? Math.round(until - nowSec) : 0;
  const dirty = rec.dirty === true || rec.dirty === "yes" || failures > 0;
  let hourly = 0;
  if (Array.isArray(rec.rotations)) {
    for (const ts of rec.rotations) {
      if (epochSec(ts) > hourAgo) hourly += 1;
    }
  }
  let model = "";
  if (rec.last429 && typeof rec.last429 === "object") {
    model = rec.last429.model ? String(rec.last429.model) : "";
  } else if (typeof rec.last429 === "string") {
    model = rec.last429;
  }
  rows.push(
    "  #" + i +
    " dirty=" + (dirty ? "yes" : "no") +
    " cooldown=" + cooling + "s" +
    " failures=" + failures +
    " rotations1h=" + hourly +
    (rec.pendingVerify === true ? " pending=yes" : "") +
    " last429=" + (model || "(none)")
  );
}
if (rows.length === 0) process.exit(0);
process.stdout.write("\n=== keep-cold scheduler (last known per-relay state) ===\n");
process.stdout.write(rows.join("\n") + "\n");
' 2>/dev/null || true
fi

TS_IP="$(mesh_ip)"
[ -z "$TS_IP" ] && TS_IP="<tailscale-ip>"

# One URL for the whole pool. Tunnels mode publishes no host port, so its
# tunnel URL is the only way in; a mesh install dials the bind the generator
# wrote, with a fix-up hint when that bind is loopback (not reachable from the
# tailnet). A direct-public install prints its public address with the Basic
# credentials embedded, because ordinary proxy clients read them from userinfo.
TUNNEL_0="$(tunnel_url 0)"
CLIENT_URL=""
echo ""
if [ -n "$TUNNEL_0" ]; then
  CLIENT_URL="$TUNNEL_0"
  echo "=== Relay URL (public HTTPS, one for the whole pool) ==="
elif [ -z "$ROUTER_BIND" ]; then
  echo "=== Relay URL: not host-published ==="
  echo "(tunnels mode: docker logs warp-relay-tunnel-0 for its trycloudflare.com URL;"
  echo " mesh mode: INGRESS_BIND=<tailscale-ip> ./generate-compose.sh ${COUNT})"
elif [ "$ROUTER_BIND" = "127.0.0.1" ]; then
  echo "=== Relay URL: router bound to 127.0.0.1 (not reachable from the tailnet) ==="
  echo "(re-run: INGRESS_BIND=${TS_IP} ./generate-compose.sh ${COUNT} && docker compose up -d)"
  CLIENT_URL="http://127.0.0.1:${ROUTER_PORT}"
else
  if [ "$ROUTER_BIND" = "0.0.0.0" ]; then
    HOST_ADDR="$TS_IP"
    if [ -n "$DIRECT_PUBLIC" ]; then
      HOST_ADDR="$(curl -4 -s -m 5 https://api.ipify.org 2>/dev/null || true)"
      [ -z "$HOST_ADDR" ] && HOST_ADDR="$TS_IP"
    fi
  else
    HOST_ADDR="$ROUTER_BIND"
  fi
  AUTH_PREFIX=""
  [ -n "$PROXY_AUTH_VALUE" ] && AUTH_PREFIX="${PROXY_AUTH_VALUE}@"
  CLIENT_URL="http://${AUTH_PREFIX}${HOST_ADDR}:${ROUTER_PORT}"
  if [ -n "$DIRECT_PUBLIC" ]; then
    echo "=== Relay URL (public, proxy credentials enforced) ==="
  else
    echo "=== Relay URL (mesh-VPN direct) ==="
  fi
fi

if [ -n "$CLIENT_URL" ]; then
  echo "  ${CLIENT_URL}"
  echo ""
  echo "One URL, rota-style: every relay is a lane behind it, picked per request."
  echo "Health check:  curl -s -x ${CLIENT_URL} https://cloudflare.com/cdn-cgi/trace"
fi
